async def get_project_file(
    project_id: str,
    filename: str,
    project_service: ProjectService = Depends(get_project_service)
):
    """Get a project file by filename."""
    try:
        from pathlib import Path
        import json
        from fastapi.responses import FileResponse

        # Build the file path - using the correct project directory
        from ...core.path_utils import get_project_directory
        project_root = get_project_directory(project_id)

        # Try multiple candidate paths
        possible_paths = [
            project_root / "raw" / filename,  # raw files
            project_root / "metadata" / filename,  # metadata files
            project_root / filename,  # directly under the project root
        ]

        file_path = None
        for path in possible_paths:
            if path.exists():
                file_path = path
                break

        if not file_path:
            raise HTTPException(status_code=404, detail="File not found")

        # Return different responses by file type
        if filename.endswith('.json'):
            # Return JSON data
            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
            return data
        else:
            # Other files (e.g. video) return a stream
            media_type = "video/mp4" if filename.endswith('.mp4') else "application/octet-stream"
            return FileResponse(
                path=str(file_path),
                filename=filename,
                media_type=media_type,
                headers={
                    "Accept-Ranges": "bytes",  # range requests for video playback
                    "Cache-Control": "public, max-age=3600"  # cache for 1 hour
                }
            )
    except HTTPException:
        raise
    except Exception as e:
        logger.exception("Failed to get project file: %s/%s", project_id, filename)
        raise HTTPException(status_code=500, detail="Failed to get project file; please try again later")


